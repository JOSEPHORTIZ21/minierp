-- =====================================================================
-- Mini-ERP · Esquema inicial, seguridad (RLS) y datos semilla
-- =====================================================================
-- Arquitectura: el navegador NUNCA habla con Supabase. Solo el backend
-- Spring Boot (Render) se conecta, con el usuario dueño de las tablas,
-- que no está sujeto a RLS. Por eso:
--   * Las tablas viven en el esquema "minierp", que no está expuesto por la
--     API REST automática de Supabase (PostgREST solo expone "public").
--   * RLS está activo en TODAS las tablas y no existe ninguna política para
--     los roles "anon" ni "authenticated": aunque alguien expusiera el esquema
--     o filtrara la anon key, cualquier SELECT/INSERT/UPDATE/DELETE devuelve
--     cero filas o falla.
--   * Además se revocan los privilegios de esos roles sobre el esquema.
--
-- Esta migración es la fuente de verdad del esquema en producción
-- (el perfil "prod" usa spring.jpa.hibernate.ddl-auto=validate).
--
-- Si el esquema "minierp" ya existe porque Hibernate lo creó con
-- ddl-auto=update, los CREATE TABLE IF NOT EXISTS no lo modifican y las
-- restricciones CHECK nuevas no se agregan. Para aplicarla completa:
--   drop schema minierp cascade;   -- borra los datos (solo había semilla)
-- y luego ejecuta este archivo.
-- =====================================================================

create schema if not exists minierp;

-- ---------------------------------------------------------------------
-- Tablas
-- ---------------------------------------------------------------------

create table if not exists minierp.categorias (
    id          bigint generated by default as identity primary key,
    nombre      varchar(80)  not null,
    descripcion varchar(255),
    constraint uk_categorias_nombre unique (nombre)
);

create table if not exists minierp.productos (
    id             bigint generated by default as identity primary key,
    codigo         varchar(30)    not null,
    nombre         varchar(120)   not null,
    descripcion    varchar(255),
    precio_compra  numeric(14, 2) not null,
    precio_venta   numeric(14, 2) not null,
    porcentaje_iva numeric(5, 2)  not null,
    stock          integer        not null default 0,
    stock_minimo   integer        not null default 0,
    activo         boolean        not null default true,
    categoria_id   bigint         not null references minierp.categorias (id) on delete restrict,
    constraint uk_productos_codigo unique (codigo),
    constraint ck_productos_precios check (precio_compra > 0 and precio_venta > 0),
    constraint ck_productos_iva check (porcentaje_iva between 0 and 100),
    constraint ck_productos_stock check (stock >= 0 and stock_minimo >= 0)
);
create index if not exists ix_productos_categoria on minierp.productos (categoria_id);

create table if not exists minierp.clientes (
    id        bigint generated by default as identity primary key,
    documento varchar(20)  not null,
    nombre    varchar(120) not null,
    telefono  varchar(20),
    email     varchar(120),
    direccion varchar(200),
    constraint uk_clientes_documento unique (documento)
);

create table if not exists minierp.proveedores (
    id           bigint generated by default as identity primary key,
    nit          varchar(20)  not null,
    razon_social varchar(150) not null,
    telefono     varchar(20),
    email        varchar(120),
    direccion    varchar(200),
    constraint uk_proveedores_nit unique (nit)
);

create table if not exists minierp.ventas (
    id         bigint generated by default as identity primary key,
    numero     varchar(20),
    fecha      timestamp(6)   not null,
    cliente_id bigint references minierp.clientes (id) on delete restrict,
    subtotal   numeric(14, 2) not null,
    total_iva  numeric(14, 2) not null,
    total      numeric(14, 2) not null,
    estado     varchar(15)    not null,
    constraint uk_ventas_numero unique (numero),
    constraint ck_ventas_estado check (estado in ('COMPLETADA', 'ANULADA')),
    constraint ck_ventas_montos check (subtotal >= 0 and total_iva >= 0 and total >= 0)
);
create index if not exists ix_ventas_fecha on minierp.ventas (fecha);
create index if not exists ix_ventas_cliente on minierp.ventas (cliente_id);

create table if not exists minierp.detalles_venta (
    id              bigint generated by default as identity primary key,
    venta_id        bigint         not null references minierp.ventas (id) on delete cascade,
    producto_id     bigint         not null references minierp.productos (id) on delete restrict,
    cantidad        integer        not null,
    precio_unitario numeric(14, 2) not null,
    porcentaje_iva  numeric(5, 2)  not null,
    subtotal        numeric(14, 2) not null,
    valor_iva       numeric(14, 2) not null,
    total           numeric(14, 2) not null,
    constraint ck_detalles_venta_cantidad check (cantidad > 0)
);
create index if not exists ix_detalles_venta_venta on minierp.detalles_venta (venta_id);
create index if not exists ix_detalles_venta_producto on minierp.detalles_venta (producto_id);

create table if not exists minierp.compras (
    id             bigint generated by default as identity primary key,
    numero_factura varchar(40)    not null,
    fecha          timestamp(6)   not null,
    proveedor_id   bigint         not null references minierp.proveedores (id) on delete restrict,
    subtotal       numeric(14, 2) not null,
    total_iva      numeric(14, 2) not null,
    total          numeric(14, 2) not null,
    constraint uk_compras_proveedor_factura unique (proveedor_id, numero_factura)
);
create index if not exists ix_compras_fecha on minierp.compras (fecha);

create table if not exists minierp.detalles_compra (
    id             bigint generated by default as identity primary key,
    compra_id      bigint         not null references minierp.compras (id) on delete cascade,
    producto_id    bigint         not null references minierp.productos (id) on delete restrict,
    cantidad       integer        not null,
    costo_unitario numeric(14, 2) not null,
    porcentaje_iva numeric(5, 2)  not null,
    subtotal       numeric(14, 2) not null,
    valor_iva      numeric(14, 2) not null,
    total          numeric(14, 2) not null,
    constraint ck_detalles_compra_cantidad check (cantidad > 0)
);
create index if not exists ix_detalles_compra_compra on minierp.detalles_compra (compra_id);
create index if not exists ix_detalles_compra_producto on minierp.detalles_compra (producto_id);

create table if not exists minierp.movimientos_inventario (
    id               bigint generated by default as identity primary key,
    producto_id      bigint       not null references minierp.productos (id) on delete restrict,
    tipo             varchar(10)  not null,
    concepto         varchar(25)  not null,
    cantidad         integer      not null,
    stock_anterior   integer      not null,
    stock_resultante integer      not null,
    referencia       varchar(40),
    observacion      varchar(255),
    fecha            timestamp(6) not null,
    constraint ck_movimientos_tipo check (tipo in ('ENTRADA', 'SALIDA')),
    constraint ck_movimientos_concepto check (concepto in
        ('INVENTARIO_INICIAL', 'COMPRA', 'VENTA', 'ANULACION_VENTA', 'AJUSTE')),
    constraint ck_movimientos_cantidad check (cantidad > 0 and stock_resultante >= 0)
);
create index if not exists ix_movimientos_producto_fecha on minierp.movimientos_inventario (producto_id, fecha, id);

-- ---------------------------------------------------------------------
-- Seguridad: RLS en todas las tablas, sin políticas para roles públicos
-- ---------------------------------------------------------------------

alter table minierp.categorias             enable row level security;
alter table minierp.productos              enable row level security;
alter table minierp.clientes               enable row level security;
alter table minierp.proveedores            enable row level security;
alter table minierp.ventas                 enable row level security;
alter table minierp.detalles_venta         enable row level security;
alter table minierp.compras                enable row level security;
alter table minierp.detalles_compra        enable row level security;
alter table minierp.movimientos_inventario enable row level security;

-- Sin "create policy": el acceso por defecto con RLS activo es DENEGAR.
-- El backend usa el rol dueño de las tablas (postgres), que no está sujeto a RLS.

-- Los roles anon/authenticated existen en Supabase; en un PostgreSQL local
-- (pruebas) se omiten para que la migración también corra allí.
do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon')
       and exists (select 1 from pg_roles where rolname = 'authenticated') then
        revoke all on all tables    in schema minierp from anon, authenticated;
        revoke all on all sequences in schema minierp from anon, authenticated;
        revoke usage on schema minierp from anon, authenticated;
        alter default privileges in schema minierp revoke all on tables    from anon, authenticated;
        alter default privileges in schema minierp revoke all on sequences from anon, authenticated;
    end if;
end
$$;

-- ---------------------------------------------------------------------
-- Datos semilla (solo si la base está vacía)
-- Mismos datos que DataSeeder, respetando las reglas de negocio:
-- el stock inicial y cada venta dejan su movimiento en el kardex.
-- ---------------------------------------------------------------------

do $$
declare
    v_venta    record;
    v_item     record;
    v_venta_id bigint;
    v_sub      numeric(14, 2);
    v_iva      numeric(14, 2);
    v_subtotal numeric(14, 2);
    v_total_iva numeric(14, 2);
    v_numero   varchar(20);
begin
    if exists (select 1 from minierp.categorias) then
        raise notice 'minierp ya tiene datos: se omite la semilla';
        return;
    end if;

    insert into minierp.categorias (nombre, descripcion) values
        ('Abarrotes', 'Granos, aceites y despensa'),
        ('Bebidas',   'Agua, jugos y gaseosas'),
        ('Aseo',      'Limpieza del hogar'),
        ('Papelería', 'Útiles escolares y de oficina');

    create temp table _semilla_productos (
        codigo varchar(30), nombre varchar(120), compra numeric, venta numeric,
        iva numeric, stock int, minimo int, categoria varchar(80)
    ) on commit drop;
    insert into _semilla_productos values
        ('ABA-001', 'Arroz blanco 500 g',              1800,  2500,  0, 120, 30, 'Abarrotes'),
        ('ABA-002', 'Aceite vegetal 1 L',              7200,  9500,  5,  40, 10, 'Abarrotes'),
        ('ABA-003', 'Café molido 500 g',              11000, 14900,  5,  25,  8, 'Abarrotes'),
        ('ABA-004', 'Azúcar 1 kg',                     3600,  4800,  5,   6, 15, 'Abarrotes'),
        ('BEB-001', 'Agua sin gas 600 ml',              900,  1800, 19, 200, 50, 'Bebidas'),
        ('BEB-002', 'Jugo de naranja 1 L',             3800,  5500, 19,   4, 10, 'Bebidas'),
        ('ASE-001', 'Detergente en polvo 1 kg',        8200, 11500, 19,  35, 10, 'Aseo'),
        ('ASE-002', 'Jabón de loza 500 g',             3100,  4500, 19,  60, 15, 'Aseo'),
        ('PAP-001', 'Cuaderno cuadriculado 100 hojas', 2900,  4500, 19,  80, 20, 'Papelería'),
        ('PAP-002', 'Bolígrafo negro',                  600,  1200, 19, 150, 40, 'Papelería');

    insert into minierp.productos
        (codigo, nombre, precio_compra, precio_venta, porcentaje_iva, stock, stock_minimo, activo, categoria_id)
    select s.codigo, s.nombre, s.compra, s.venta, s.iva, s.stock, s.minimo, true, c.id
    from _semilla_productos s
    join minierp.categorias c on c.nombre = s.categoria
    order by s.codigo;

    -- Inventario inicial en el kardex
    insert into minierp.movimientos_inventario
        (producto_id, tipo, concepto, cantidad, stock_anterior, stock_resultante, referencia, observacion, fecha)
    select p.id, 'ENTRADA', 'INVENTARIO_INICIAL', p.stock, 0, p.stock, p.codigo, 'Inventario inicial', localtimestamp
    from minierp.productos p
    where p.stock > 0;

    insert into minierp.clientes (documento, nombre, telefono, email, direccion) values
        ('1121000001', 'Laura Martínez', '3101234567', 'laura@example.com', 'Barrio Centro'),
        ('900123456', 'Distribuidora El Llano S.A.S.', '6086712345', 'compras@elllano.example.com', 'Km 5 vía Puerto López');

    insert into minierp.proveedores (nit, razon_social, telefono, email, direccion) values
        ('900555111-2', 'Mayorista Andino S.A.S.', '6017001122', 'ventas@mayoristaandino.example.com', 'Bogotá'),
        ('901222333-4', 'Aseo Total Ltda.', '6045556677', 'pedidos@aseototal.example.com', 'Medellín');

    -- Tres ventas para que el dashboard no arranque vacío
    create temp table _semilla_ventas (n int, documento varchar(20), codigo varchar(30), cantidad int) on commit drop;
    insert into _semilla_ventas values
        (1, '1121000001', 'ABA-001', 4), (1, '1121000001', 'ABA-003', 1),
        (2, null,         'BEB-001', 6), (2, null,         'PAP-001', 3),
        (3, null,         'ASE-001', 2), (3, null,         'ABA-001', 2);

    for v_venta in select distinct n, documento from _semilla_ventas order by n loop
        insert into minierp.ventas (fecha, cliente_id, subtotal, total_iva, total, estado)
        values (localtimestamp,
                (select id from minierp.clientes where documento = v_venta.documento),
                0, 0, 0, 'COMPLETADA')
        returning id into v_venta_id;
        v_numero := 'FV-' || lpad(v_venta_id::text, 6, '0');
        v_subtotal := 0;
        v_total_iva := 0;

        -- En orden de id de producto, igual que VentaService
        for v_item in
            select p.id, p.precio_venta, p.porcentaje_iva, p.stock, s.cantidad
            from _semilla_ventas s
            join minierp.productos p on p.codigo = s.codigo
            where s.n = v_venta.n
            order by p.id
        loop
            v_sub := round(v_item.precio_venta * v_item.cantidad, 2);
            v_iva := round(v_sub * v_item.porcentaje_iva / 100, 2);

            insert into minierp.detalles_venta
                (venta_id, producto_id, cantidad, precio_unitario, porcentaje_iva, subtotal, valor_iva, total)
            values (v_venta_id, v_item.id, v_item.cantidad, v_item.precio_venta, v_item.porcentaje_iva,
                    v_sub, v_iva, v_sub + v_iva);

            insert into minierp.movimientos_inventario
                (producto_id, tipo, concepto, cantidad, stock_anterior, stock_resultante, referencia, fecha)
            values (v_item.id, 'SALIDA', 'VENTA', v_item.cantidad, v_item.stock,
                    v_item.stock - v_item.cantidad, v_numero, localtimestamp);

            update minierp.productos set stock = stock - v_item.cantidad where id = v_item.id;

            v_subtotal := v_subtotal + v_sub;
            v_total_iva := v_total_iva + v_iva;
        end loop;

        update minierp.ventas
        set numero = v_numero, subtotal = v_subtotal, total_iva = v_total_iva, total = v_subtotal + v_total_iva
        where id = v_venta_id;
    end loop;
end
$$;
