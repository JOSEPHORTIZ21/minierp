-- =====================================================================
-- Mini-ERP · Usuarios del sistema (login con roles ADMIN y CAJERO)
-- =====================================================================
-- Solo el backend accede a esta tabla (igual que al resto del esquema):
-- RLS activo y sin políticas para anon/authenticated.
--
-- No se insertan usuarios aquí: una contraseña en un archivo versionado
-- quedaría expuesta. El primer administrador lo crea el backend al arrancar
-- a partir de las variables de entorno ADMIN_EMAIL y ADMIN_PASSWORD
-- (solo cuando la tabla está vacía).
-- =====================================================================

create table if not exists minierp.usuarios (
    id         bigint generated by default as identity primary key,
    email      varchar(120) not null,
    nombre     varchar(120) not null,
    clave_hash varchar(100) not null,
    rol        varchar(10)  not null,
    activo     boolean      not null default true,
    creado_en  timestamp(6) not null,
    constraint uk_usuarios_email unique (email),
    constraint ck_usuarios_rol check (rol in ('ADMIN', 'CAJERO')),
    constraint ck_usuarios_email_minusculas check (email = lower(email))
);

alter table minierp.usuarios enable row level security;

do $$
begin
    if exists (select 1 from pg_roles where rolname = 'anon')
       and exists (select 1 from pg_roles where rolname = 'authenticated') then
        revoke all on minierp.usuarios from anon, authenticated;
    end if;
end
$$;
